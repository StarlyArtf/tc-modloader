/* Offline test for the per-width text layer (plan 5.3 and 6.4.1).

   The binary32 half of the text layer has its own golden vectors
   (tests/float-decimal.cpp, generated by tools/float-decimal-vectors.py).  This
   case covers the two widths that arrived with the width cut:

   - the hex form has each format's own digit count (four, eight, sixteen);
   - binary64 formats with Ryu's d2s, and every sampled pattern has to round-trip
     through the text and back to the same bits;
   - binary16 formats its exact binary32 image and then shortens the digits, so
     *every* one of the 65536 patterns is checked to round-trip (0.1 in binary16
     has to read "0.1", not the binary32 spelling "0.099975586"), and a table of
     named values pins the exact strings;
   - a small buffer stays NUL-terminated and the returned length still counts
     what the text would have been.

   Parsing back is the host's own path in reverse: fast_float to binary32, then
   SoftFloat's conversion to the target width - the same pair fp/decimal.cpp uses
   for its round-trip search, which is what makes this a check of the formatting
   rather than a second implementation of it. */

#include "../examples/float-ops/fp/decimal.hpp"
#include "../examples/float-ops/fp/environment.hpp"
#include "../examples/float-ops/fp/format.hpp"

#include "fast_float/fast_float.h"

#include <cstdint>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

namespace {

using tcfp::DisplayMode;
using tcfp::FPRounding;
using tcfp::softfloat_environment::SoftFloatOperation;

constexpr int kMaxReportedFailures = 25;

std::string hexOf(uint32_t format, uint64_t bits) {
    char buffer[24] = {};
    std::snprintf(buffer, sizeof(buffer), "0x%0*llX", static_cast<int>(format / 4),
                  static_cast<unsigned long long>(bits));
    return buffer;
}

uint16_t toF16(uint32_t bits) {
    float32_t value;
    value.v = bits;
    SoftFloatOperation operation(FPRounding::nearest_even);
    float16_t half = f32_to_f16(value);
    return half.v;
}

/* Decimal text back to a pattern of one width.  A text that fast_float refuses
   leaves *bits alone; the callers report that as a failure of its own. */
bool parseTo(uint32_t format, const char* text, uint64_t* bits) {
    float value = 0.f;
    const size_t length = std::strlen(text);
    const auto answer = fast_float::from_chars(text, text + length, value);
    if (answer.ec != std::errc() || answer.ptr != text + length) return false;
    uint32_t image = 0;
    std::memcpy(&image, &value, sizeof(image));
    if (format == tcfp::kFormatBinary16) {
        *bits = toF16(image);
        return true;
    }
    if (format == tcfp::kFormatBinary32) {
        *bits = image;
        return true;
    }
    return false; /* binary64 has its own reader below */
}

bool parseTo64(const char* text, uint64_t* bits) {
    double value = 0.0;
    const size_t length = std::strlen(text);
    const auto answer = fast_float::from_chars(text, text + length, value);
    if (answer.ec != std::errc() || answer.ptr != text + length) return false;
    std::memcpy(bits, &value, sizeof(value));
    return true;
}

bool isNaN(uint32_t format, uint64_t bits) {
    const tcfp::Layout& layout = tcfp::layoutFor(format);
    return (bits & layout.exponent_mask) == layout.exponent_mask &&
           (bits & layout.significand_mask) != 0;
}

struct Named {
    uint32_t format;
    uint64_t bits;
    const char* shortest;
    const char* scientific;
    const char* hex;
};

/* Values whose exact spelling is part of the contract: 1.0 in every width (the
   default a fresh Constant carries), the values an editor round-trips most,
   the largest finite value of each width, the signed zero and the specials. */
const Named kNamed[] = {
    {16, UINT64_C(0x3C00), "1", "1.0e+00", "0x3C00"},
    {16, UINT64_C(0x3E00), "1.5", "1.5e+00", "0x3E00"},
    {16, UINT64_C(0xC000), "-2", "-2.0e+00", "0xC000"},
    {16, UINT64_C(0x2E66), "0.1", "1.0e-01", "0x2E66"},
    {16, UINT64_C(0x3555), "0.3333", "3.333e-01", "0x3555"},
    /* 65504 is the largest binary16; the shortest decimal that round-trips to it
       is 65500, the same way Ryu prints 3.4028235E38 for the largest binary32
       (three digits here, and "65500" parses back to 65504). */
    {16, UINT64_C(0x7BFF), "65500", "6.55e+04", "0x7BFF"},
    {16, UINT64_C(0x0001), "6.0e-08", "6.0e-08", "0x0001"},
    {16, UINT64_C(0x8000), "-0", "-0.0e+00", "0x8000"},
    {16, UINT64_C(0x7C00), "inf", "inf", "0x7C00"},
    {16, UINT64_C(0xFC00), "-inf", "-inf", "0xFC00"},
    {16, UINT64_C(0x7E00), "nan", "nan", "0x7E00"},
    {32, UINT64_C(0x3F800000), "1", "1.0e+00", "0x3F800000"},
    {32, UINT64_C(0x3DCCCCCD), "0.1", "1.0e-01", "0x3DCCCCCD"},
    {32, UINT64_C(0x80000000), "-0", "-0.0e+00", "0x80000000"},
    {64, UINT64_C(0x3FF0000000000000), "1", "1.0e+00", "0x3FF0000000000000"},
    {64, UINT64_C(0x3FB999999999999A), "0.1", "1.0e-01", "0x3FB999999999999A"},
    {64, UINT64_C(0x3FD5555555555555), "0.3333333333333333", "3.333333333333333e-01",
     "0x3FD5555555555555"},
    {64, UINT64_C(0x7FEFFFFFFFFFFFFF), "1.7976931348623157e+308",
     "1.7976931348623157e+308", "0x7FEFFFFFFFFFFFFF"},
    {64, UINT64_C(0x0000000000000001), "5.0e-324", "5.0e-324", "0x0000000000000001"},
    {64, UINT64_C(0x8000000000000000), "-0", "-0.0e+00", "0x8000000000000000"},
    {64, UINT64_C(0x7FF0000000000000), "inf", "inf", "0x7FF0000000000000"},
    {64, UINT64_C(0x7FF8000000000000), "nan", "nan", "0x7FF8000000000000"},
};

void checkNamed(std::vector<std::string>& failures, int& checked) {
    for (const Named& named : kNamed) {
        char shortest[64] = {};
        char scientific[64] = {};
        char hex[32] = {};
        char combined[96] = {};
        tcfp::format_shortest_for(named.format, named.bits, shortest, sizeof(shortest));
        tcfp::format_scientific_for(named.format, named.bits, scientific,
                                    sizeof(scientific));
        tcfp::format_hex_for(named.format, named.bits, hex, sizeof(hex));
        tcfp::format_value_for(named.format, named.bits, DisplayMode::decimal_and_hex,
                               combined, sizeof(combined));
        ++checked;
        const std::string expected_combined =
            std::string(named.shortest) + " " + named.hex;
        if (std::strcmp(shortest, named.shortest) == 0 &&
            std::strcmp(scientific, named.scientific) == 0 &&
            std::strcmp(hex, named.hex) == 0 && std::string(combined) == expected_combined)
            continue;
        if (static_cast<int>(failures.size()) >= kMaxReportedFailures) continue;
        char detail[360] = {};
        std::snprintf(detail, sizeof(detail),
                      "FP%u %s: expected \"%s\"/\"%s\"/\"%s\", got \"%s\"/\"%s\"/\"%s\"",
                      named.format, hexOf(named.format, named.bits).c_str(),
                      named.shortest, named.scientific, named.hex, shortest, scientific,
                      hex);
        failures.push_back(detail);
    }
}

/* Every binary16 pattern: the formatted text has to parse back to the pattern it
   came from (a NaN formats as "nan", which is the lossy case by design), and the
   spelling may never need more than binary16's five significant digits. */
void checkBinary16RoundTrip(std::vector<std::string>& failures, int& checked) {
    for (uint32_t pattern = 0; pattern <= 0xFFFFu; ++pattern) {
        char text[64] = {};
        tcfp::format_shortest_for(tcfp::kFormatBinary16, pattern, text, sizeof(text));
        ++checked;
        if (isNaN(tcfp::kFormatBinary16, pattern)) {
            if (std::strcmp(text, "nan") != 0)
                failures.push_back("binary16 NaN " + hexOf(16, pattern) +
                                   " formatted as \"" + text + "\"");
            continue;
        }
        uint64_t parsed = 0;
        if (parseTo(tcfp::kFormatBinary16, text, &parsed) && parsed == pattern) continue;
        if (static_cast<int>(failures.size()) >= kMaxReportedFailures) continue;
        failures.push_back("binary16 round-trip failed: " + hexOf(16, pattern) +
                           " -> \"" + text + "\" -> " + hexOf(16, parsed));
    }
}

uint32_t nextRandom(uint32_t& state) {
    state ^= state << 13;
    state ^= state >> 17;
    state ^= state << 5;
    return state;
}

/* binary64 is Ryu's d2s through this layer's own decimal layout, so the same
   round-trip check applies; NaNs format as "nan" and are excluded like above. */
void checkBinary64RoundTrip(std::vector<std::string>& failures, int& checked) {
    uint32_t state = 0x85EBCA6Bu;
    for (int index = 0; index < 20000; ++index) {
        const uint32_t high = nextRandom(state);
        const uint32_t low = nextRandom(state);
        const uint64_t bits = (static_cast<uint64_t>(high) << 32) | low;
        if (isNaN(tcfp::kFormatBinary64, bits)) continue;
        char text[64] = {};
        tcfp::format_shortest_for(tcfp::kFormatBinary64, bits, text, sizeof(text));
        ++checked;
        uint64_t parsed = 0;
        if (parseTo64(text, &parsed) && parsed == bits) continue;
        if (static_cast<int>(failures.size()) >= kMaxReportedFailures) continue;
        failures.push_back("binary64 round-trip failed: " + hexOf(64, bits) + " -> \"" +
                           text + "\" -> " + hexOf(64, parsed));
    }
}

/* The buffer contract every formatter shares (plan 5.3): never write past the
   end, always terminate, and still report the length the text would have had. */
void checkBuffers(std::vector<std::string>& failures) {
    char small[5] = {'x', 'x', 'x', 'x', 'x'};
    const size_t written = tcfp::format_value_for(
        tcfp::kFormatBinary64, UINT64_C(0x3FF0000000000000), DisplayMode::decimal_and_hex,
        small, sizeof(small));
    if (small[sizeof(small) - 1] != '\0')
        failures.push_back("a small binary64 buffer was not NUL-terminated");
    if (written <= sizeof(small) - 1)
        failures.push_back("the binary64 formatter did not report the truncated length");

    char tiny[3] = {'x', 'x', 'x'};
    tcfp::format_hex_for(tcfp::kFormatBinary64, UINT64_C(0x3FF0000000000000), tiny,
                         sizeof(tiny));
    if (tiny[sizeof(tiny) - 1] != '\0')
        failures.push_back("a small hex buffer was not NUL-terminated");
}

}  // namespace

int main() {
    std::vector<std::string> failures;
    int namedChecked = 0;
    int halfChecked = 0;
    int doubleChecked = 0;

    checkNamed(failures, namedChecked);
    checkBinary16RoundTrip(failures, halfChecked);
    checkBinary64RoundTrip(failures, doubleChecked);
    checkBuffers(failures);

    if (!failures.empty()) {
        for (const std::string& failure : failures)
            std::printf("FAIL %s\n", failure.c_str());
        if (static_cast<int>(failures.size()) >= kMaxReportedFailures)
            std::printf("     (report truncated at %d failures)\n", kMaxReportedFailures);
        std::printf("FAIL float-ops width text: %zu failing check(s)\n", failures.size());
        return 1;
    }

    std::printf("PASS float-ops width text: %d named spellings (FP16/FP32/FP64 shortest, "
                "scientific and hex), %d binary16 patterns round-tripped, %d binary64 "
                "patterns round-tripped, small buffers safe\n",
                namedChecked, halfChecked, doubleChecked);
    return 0;
}
